import { readFileSync, writeFileSync } from 'node:fs';

// Keep the page overview and the standalone interactive diagram on the same snapshot.
const source = new URL('../public/architecture-diagram.html', import.meta.url);
const html = readFileSync(source, 'utf8');
const css = html.match(/<style>([\s\S]*?)<\/style>/)?.[1];
const graph = html.match(/<svg\b[^>]*viewBox="0 0 1360 650"[\s\S]*?<\/svg>/)?.[0];
if (!css || !graph) throw new Error('Architecture snapshot is missing its stylesheet or runtime graph.');

const svg = graph.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" width="1360" height="650" data-theme="dark" ')
  .replace(/(<svg\b[^>]*>)/, `$1\n<style><![CDATA[${css}\n:root { font-family: Consolas, ui-monospace, monospace; background: #020617; min-width: 0; }\n]]></style>`)
  .replace(/ tabindex="0"| role="button"| aria-pressed="false"/g, '');
writeFileSync(new URL('../public/assets/architecture-overview.svg', import.meta.url), `<!-- Generated by scripts/export-architecture.mjs. -->\n${svg}\n`);
